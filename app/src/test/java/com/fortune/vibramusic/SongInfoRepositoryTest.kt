package com.fortune.vibramusic

import com.fortune.vibramusic.data.SongInfoParser
import com.fortune.vibramusic.data.compactCount
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.jsonObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Test
import java.io.File

class SongInfoRepositoryTest {

    @Test
    fun compactCount_formatsPlainNumbers() {
        assertEquals("0", compactCount("0"))
        assertEquals("950", compactCount("950"))
        assertEquals("1K", compactCount("1000"))
        assertEquals("100K", compactCount("100456"))
        assertEquals("999K", compactCount("999999"))
        assertEquals("1.8B", compactCount("1830260267"))
    }

    @Test
    fun compactCount_formatsNumbersWithCommasAndDescriptors() {
        assertEquals("315K", compactCount("315,741 views"))
        assertEquals("1.8B", compactCount("1,830,261,093 views"))
        assertEquals("5.7K", compactCount("5.7K"))
        assertEquals("19M", compactCount("19M likes"))
        assertEquals("112", compactCount("112"))
        assertEquals("2.4M", compactCount("2.4M"))
    }

    @Test
    fun parsesNextResponseCorrectly() {
        val sampleJson = """
        {
          "contents": {
            "twoColumnWatchNextResults": {
              "results": {
                "results": {
                  "contents": [
                    {
                      "videoPrimaryInfoRenderer": {
                        "viewCount": {
                          "videoViewCountRenderer": {
                            "viewCount": { "simpleText": "315,741 views" }
                          }
                        },
                        "videoActions": {
                          "menuRenderer": {
                            "topLevelButtons": [
                              {
                                "segmentedLikeDislikeButtonViewModel": {
                                  "likeButtonViewModel": {
                                    "likeButtonViewModel": {
                                      "toggleButtonViewModel": {
                                        "toggleButtonViewModel": {
                                          "defaultButtonViewModel": {
                                            "buttonViewModel": {
                                              "title": "5.7K"
                                            }
                                          }
                                        }
                                      }
                                    }
                                  }
                                }
                              }
                            ]
                          }
                        }
                      }
                    }
                  ]
                }
              }
            }
          },
          "engagementPanels": [
            {
              "engagementPanelSectionListRenderer": {
                "panelIdentifier": "engagement-panel-comments-section",
                "header": {
                  "engagementPanelTitleHeaderRenderer": {
                    "contextualInfo": {
                      "runs": [
                        { "text": "112" }
                      ]
                    }
                  }
                }
              }
            }
          ]
        }
        """.trimIndent()

        val json = Json.parseToJsonElement(sampleJson).jsonObject
        val info = SongInfoParser.parseNext(json, "test_video_id")

        assertEquals("315K", info.views)
        assertEquals("5.7K", info.likes)
        assertEquals("112", info.comments)
        assertFalse(info.failed)
    }

    @Test
    fun parsesPlayerResponseCorrectly() {
        val sampleJson = """
        {
          "videoDetails": {
            "videoId": "test_video_id",
            "viewCount": "315741",
            "shortDescription": "Provided to YouTube\nReleased on: 2020-05-14\nAuto-generated by YouTube."
          }
        }
        """.trimIndent()

        val json = Json.parseToJsonElement(sampleJson).jsonObject
        val info = SongInfoParser.parsePlayer(json)

        assertEquals("315K", info.views)
        assertEquals("2020-05-14", info.releaseDate)
        assertFalse(info.failed)
    }
}
